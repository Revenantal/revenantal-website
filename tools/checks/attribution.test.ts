import { describe, expect, it } from "vitest";
import { attributionViolations } from "./attribution";

describe("authorship policy", () => {
  it.each([
    "feat(data): load project content",
    "fix(tv): ignore an obsolete session callback",
    "docs: explain the no AI attribution rule",
    "chore: add the generated asset manifest",
  ])("allows ordinary project text: %s", (message) => {
    expect(attributionViolations(message)).toEqual([]);
  });

  it.each([
    "feat: change\n\nCo-Authored-By: Example <example@example.invalid>",
    "fix: change\n  co-authored-by : Example",
    "docs: change\nGenerated with an assistant",
    "feat: change\nGENERATED BY an assistant",
    "AI-generated contribution",
    "https://chatgpt.com/share/fixture",
    "https://claude.ai/chat/fixture",
  ])("rejects attribution regardless of case: %s", (message) => {
    expect(attributionViolations(message).length).toBeGreaterThan(0);
  });
});
